#!/bin/sh
# Writes Zone C's production mark key, K, to a Swift file that git ignores.
#
#   sh tools/zonec/make_key.sh [output-file]
#
# The repository is public and K is compiled into the app, so K must never be
# committed (BUILD-PLAN.md, section 5, risk 1). The default output is
# App/PeaceGarden/ZoneC/ZoneCProductionKey.swift, which .gitignore names. A
# Release build does not compile without it; Debug builds and tests use the
# fixed test key in ZoneCKey.swift and never read it.
#
# Run it once, on the machine that archives. K must then stay the same in every
# build that ships: a build with a different K cannot recognise the space seeds
# already in the pool, and they would be passed over. So this refuses to
# overwrite a file that exists. Keep a copy somewhere that is not this
# repository (a password manager, an encrypted note), and copy it into any other
# checkout that archives. After it is written, run `xcodegen generate`, because
# the project lists its source files when it is generated.
#
# It never prints K.
set -eu

root=$(cd "$(dirname "$0")/../.." && pwd)
out=${1:-"$root/App/PeaceGarden/ZoneC/ZoneCProductionKey.swift"}

if [ -e "$out" ]; then
  echo "make_key: $out already exists; not replacing it." >&2
  echo "  A new K orphans every space seed signed with the old one. If that is" >&2
  echo "  what you want, delete the file yourself first." >&2
  exit 1
fi

# Inside this repository the file must be ignored, or `git add -A` could commit
# it. check-ignore exits 1 for a path that is not ignored (or is tracked) and
# 128 for one outside the repository, which is fine.
rc=0
git -C "$root" check-ignore -q -- "$out" 2>/dev/null || rc=$?
if [ "$rc" -eq 1 ]; then
  echo "make_key: $out is inside the repository and not ignored by git." >&2
  echo "  Add it to .gitignore before generating a key there." >&2
  exit 1
fi

# 32 bytes from the system's random source, as 64 hex digits. Held in a shell
# variable only; the builtins below do not put it on a command line.
hex=$(od -An -v -tx1 -N32 /dev/urandom | tr -d ' \n')
if [ "${#hex}" -ne 64 ]; then
  echo "make_key: did not get 32 random bytes; nothing written." >&2
  exit 1
fi

# Owner-only from the first byte, and into a temporary file beside the target so
# that an interrupted run leaves nothing half-written under the real name.
umask 077
tmp="$out.tmp.$$"
trap 'rm -f "$tmp"' EXIT INT TERM

{
  echo "// Generated by tools/zonec/make_key.sh. Gitignored: never commit this file."
  echo "//"
  echo "// K, the key that signs the marks on space seeds. It must be the same in every"
  echo "// build that ships, so keep a copy outside the repository. Debug builds do not"
  echo "// contain it."
  echo ""
  echo "#if !DEBUG"
  echo "enum ZoneCProductionKey {"
  echo "    static let bytes: [UInt8] = ["
  # Eight bytes to a line: "0x58, " is six characters, so 48 to a line.
  printf '%s\n' "$hex" | sed 's/\(..\)/0x\1, /g' | fold -w 48 | sed 's/ *$//; s/^/        /'
  echo "    ]"
  echo "}"
  echo "#endif"
} > "$tmp"

mv "$tmp" "$out"
trap - EXIT INT TERM
echo "make_key: wrote $out (mode 600). Keep a copy outside the repository, then run xcodegen generate."
